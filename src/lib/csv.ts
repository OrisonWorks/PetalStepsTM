// Minimal RFC-4180 CSV reader: handles quoted cells, embedded commas,
// escaped quotes ("") and CRLF. No dependencies — runs in the browser.
export function parseCsv(text: string): string[][] {
  // Excel exports a UTF-8 BOM; leaving it on the first header cell breaks
  // column matching ("\uFEFFmodel" !== "model").
  text = text.replace(/^\uFEFF/, "");
  const rows: string[][] = [];
  let field = "";
  let row: string[] = [];
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      // Keep blank-ish rows out — Sheets/Excel emit trailing empties.
      if (row.some((c) => c.trim() !== "")) rows.push(row);
      row = [];
    } else {
      field += ch;
    }
  }
  row.push(field);
  if (row.some((c) => c.trim() !== "")) rows.push(row);
  return rows;
}
